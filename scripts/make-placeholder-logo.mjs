// Generates Daprova's placeholder logo mark in every format the apps need,
// from one geometry: a rounded square with a short "pre" bar and a tall
// "post" bar. Replace the outputs with the real logo when it's designed:
//   admin-web/public/daprova-mark.svg      (favicon + UI)
//   assessment-web/daprova-mark.svg, platform-web/daprova-mark.svg
//   api/src/lib/daprovaMarkPng.ts          (PNG embedded in Word reports)
// Run: node scripts/make-placeholder-logo.mjs
import fs from 'node:fs';
import zlib from 'node:zlib';

const BG = [0x0e, 0x7c, 0x5a]; // gain
const PRE = [0x9f, 0xcf, 0xbf];
const POST = [0xff, 0xff, 0xff];
const shapes = [
  { x: 0, y: 0, w: 64, h: 64, r: 14, c: BG },
  { x: 15, y: 30, w: 13, h: 20, r: 2.5, c: PRE },
  { x: 36, y: 14, w: 13, h: 36, r: 2.5, c: POST },
];

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="Daprova">\n${shapes
  .map((s) => `  <rect x="${s.x}" y="${s.y}" width="${s.w}" height="${s.h}" rx="${s.r}" fill="#${s.c.map((v) => v.toString(16).padStart(2, '0')).join('')}"/>`)
  .join('\n')}\n</svg>\n`;
for (const out of ['admin-web/public/daprova-mark.svg', 'assessment-web/daprova-mark.svg', 'platform-web/daprova-mark.svg']) fs.writeFileSync(out, svg);

function inside(s, px, py) {
  if (px < s.x || py < s.y || px > s.x + s.w || py > s.y + s.h) return false;
  const cx = Math.min(Math.max(px, s.x + s.r), s.x + s.w - s.r);
  const cy = Math.min(Math.max(py, s.y + s.r), s.y + s.h - s.r);
  return (px - cx) ** 2 + (py - cy) ** 2 <= s.r ** 2;
}

const SIZE = 256, SS = 4, scale = 64 / SIZE;
const raw = Buffer.alloc(SIZE * (SIZE * 4 + 1));
for (let y = 0; y < SIZE; y++) {
  raw[y * (SIZE * 4 + 1)] = 0;
  for (let x = 0; x < SIZE; x++) {
    let r = 0, g = 0, b = 0, a = 0;
    for (let sy = 0; sy < SS; sy++) for (let sx = 0; sx < SS; sx++) {
      const px = (x + (sx + 0.5) / SS) * scale, py = (y + (sy + 0.5) / SS) * scale;
      let c = null;
      for (const s of shapes) if (inside(s, px, py)) c = s.c;
      if (c) { r += c[0]; g += c[1]; b += c[2]; a += 255; }
    }
    const n = SS * SS, cov = a / 255;
    const o = y * (SIZE * 4 + 1) + 1 + x * 4;
    raw[o] = cov ? Math.round(r / cov) : 0; raw[o + 1] = cov ? Math.round(g / cov) : 0; raw[o + 2] = cov ? Math.round(b / cov) : 0; raw[o + 3] = Math.round(a / n);
  }
}
const crcTable = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
const crc = (buf) => { let c = 0xffffffff; for (const byte of buf) c = crcTable[(c ^ byte) & 0xff] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
const chunk = (type, data) => { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([len, td, c]); };
const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(SIZE, 0); ihdr.writeUInt32BE(SIZE, 4); ihdr[8] = 8; ihdr[9] = 6;
const png = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
fs.writeFileSync('api/src/lib/daprovaMarkPng.ts', `// Generated by scripts/make-placeholder-logo.mjs — placeholder Daprova mark\n// (256x256 PNG). Regenerate or replace when the real logo is ready.\nexport const DAPROVA_MARK_PNG_BASE64 =\n  '${png.toString('base64')}';\n`);
console.log(`svg ${svg.length} bytes, png ${png.length} bytes`);
